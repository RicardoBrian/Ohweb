export const I18N = { ko, en, zh, ru };
export function getLang() {
  let l = '';
  try { l = localStorage.getItem('ohinfo_lang') || ''; } catch { /* 저장소를 못 쓰면 브라우저 언어로 */ }
  if (I18N[l]) return l;
  const nav = String((globalThis.navigator && navigator.language) || 'ko').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('ru')) return 'ru';
  if (nav.startsWith('en')) return 'en';
  return 'ko';
}
export function setLang(l) {
  try { localStorage.setItem('ohinfo_lang', l); } catch { /* 무시 */ }
}
export function makeT(lang) {
  const dict = I18N[lang] || ko;
  return (key, vars) => {
    let v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), dict);
    if (v == null) v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), ko);
    if (v == null) return key;
    if (typeof v === 'string' && vars) v = v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    return v;
  };
}
